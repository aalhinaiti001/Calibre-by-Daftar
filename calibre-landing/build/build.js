// Builds ../index.html, a self-contained copy of ../source.html:
// Tailwind compiled from the page's own config, Lucide icons inlined as SVG,
// and the brand fonts (Latin, plus Arabic for IBM Plex Sans Arabic) embedded.
// Run: cd calibre-landing/build && npm install && npm run build
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');
const lucide = require('lucide');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'source.html');
const OUT = path.join(ROOT, 'index.html');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

async function main() {
  let html = fs.readFileSync(SRC, 'utf8');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'calibre-landing-'));

  // 1. Tailwind: compile with the config embedded in source.html
  const cfg = html.match(/tailwind\.config = (\{[\s\S]*?\n {8}\})\n/)[1].replace(/\/\/[^\n]*/g, '');
  fs.writeFileSync(path.join(tmp, 'tailwind.config.js'),
    `module.exports = Object.assign({ content: [${JSON.stringify(SRC)}] }, ${cfg});`);
  fs.writeFileSync(path.join(tmp, 'in.css'), '@tailwind base;@tailwind components;@tailwind utilities;');
  execFileSync(require.resolve('tailwindcss/lib/cli.js'),
    ['-c', path.join(tmp, 'tailwind.config.js'), '-i', path.join(tmp, 'in.css'), '-o', path.join(tmp, 'out.css'), '--minify'],
    { stdio: 'inherit' });
  const css = fs.readFileSync(path.join(tmp, 'out.css'), 'utf8');

  // 2. Fonts: fetch the Google Fonts stylesheet named in source.html and embed the faces used
  const fontsUrl = html.match(/<link href="(https:\/\/fonts\.googleapis\.com[^"]+)"/)[1].replace(/&amp;/g, '&');
  const fontsCss = await (await fetch(fontsUrl, { headers: { 'User-Agent': UA } })).text();
  const faces = [];
  for (const [, subset, block] of fontsCss.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face \{[\s\S]*?\})/g)) {
    const family = block.match(/font-family: '([^']+)'/)[1];
    const wanted = family === 'IBM Plex Sans Arabic' ? subset === 'arabic' : subset === 'latin';
    if (!wanted) continue;
    const url = block.match(/url\((https:[^)]+)\)/)[1];
    const data = Buffer.from(await (await fetch(url)).arrayBuffer());
    faces.push(block.replace(url, 'data:font/woff2;base64,' + data.toString('base64')));
  }

  // 3. Icons: <i data-lucide="name"> -> inline SVG
  const pascal = (n) => n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
  const attr = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  const render = ([tag, attrs, kids = []]) =>
    `<${tag}${Object.entries(attrs).map(([k, v]) => ` ${k}="${attr(v)}"`).join('')}>${kids.map(render).join('')}</${tag}>`;
  let icons = 0;
  html = html.replace(/<i data-lucide="([a-z0-9-]+)"([^>]*)><\/i>/g, (m, name, rest) => {
    const icon = lucide.icons[pascal(name)];
    if (!icon) throw new Error(`Unknown Lucide icon: ${name}`);
    const cls = (rest.match(/class="([^"]*)"/) || [, ''])[1];
    const [tag, attrs, kids] = icon;
    icons++;
    return render([tag, { ...attrs, class: `lucide lucide-${name} ${cls}`.trim(), ...(/aria-hidden="true"/.test(rest) ? { 'aria-hidden': 'true' } : {}) }, kids]);
  });

  // 4. Swap the runtime dependencies for the inlined versions
  html = html
    .replace(/\s*<!--\s*NOTE: Tailwind Play CDN[\s\S]*?-->/, '')
    .replace('<script src="https://cdn.tailwindcss.com"></script>', `<style>/* Tailwind CSS v3, compiled by build/build.js */\n${css}\n</style>`)
    .replace(/<script>\s*tailwind\.config = \{[\s\S]*?<\/script>/, '')
    .replace(/<link rel="preconnect"[^>]*>\s*/g, '')
    .replace(/<link href="https:\/\/fonts\.googleapis\.com[^>]*>/, `<style>/* Lora, Plus Jakarta Sans (Latin), IBM Plex Sans Arabic (Arabic), embedded */\n${faces.join('\n')}\n</style>`)
    .replace(/\s*<script src="https:\/\/unpkg\.com\/lucide[^"]*"><\/script>/, '')
    .replace(/\s*if \(window\.lucide\) lucide\.createIcons\(\);/, '');
  html = html.replace(/^<!DOCTYPE html>\n/i, '<!DOCTYPE html>\n<!-- Generated by build/build.js from source.html. Edit source.html, then rebuild. -->\n');

  fs.writeFileSync(OUT, html);
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`index.html: ${Math.round(html.length / 1024)} KB, ${icons} icons, ${faces.length} font faces`);
}

main().catch((e) => { console.error(e); process.exit(1); });
